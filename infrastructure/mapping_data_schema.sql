-- Mapping Data schema only (no folder/path mappings).
-- Each domain has its own lookup table so the business code in the main table
-- can be a real foreign key without collisions between e.g. coverage=1 and damage_type=1.
BEGIN;

CREATE TABLE IF NOT EXISTS coverage_mapping (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mapped_code VARCHAR(100) NOT NULL UNIQUE,
    mapped_title VARCHAR(500) NOT NULL,
    source_value VARCHAR(500),
    category VARCHAR(200),
    interpretation_description TEXT,
    risk_level VARCHAR(30),
    mapping_version VARCHAR(100) NOT NULL DEFAULT 'excel_001',
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS event_type_mapping (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mapped_code VARCHAR(100) NOT NULL UNIQUE,
    mapped_title VARCHAR(500) NOT NULL,
    source_value VARCHAR(500), category VARCHAR(200), interpretation_description TEXT,
    risk_level VARCHAR(30), mapping_version VARCHAR(100) NOT NULL DEFAULT 'excel_001', active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS loss_location_mapping (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mapped_code VARCHAR(100) NOT NULL UNIQUE,
    mapped_title VARCHAR(500) NOT NULL,
    source_value VARCHAR(500), category VARCHAR(200), interpretation_description TEXT,
    mapping_version VARCHAR(100) NOT NULL DEFAULT 'excel_001', active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS occupation_mapping (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mapped_code VARCHAR(100) NOT NULL UNIQUE,
    mapped_title VARCHAR(500) NOT NULL,
    source_value VARCHAR(500), category VARCHAR(200), interpretation_description TEXT,
    risk_level VARCHAR(30), mapping_version VARCHAR(100) NOT NULL DEFAULT 'excel_001', active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS occupation_group_mapping (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mapped_code VARCHAR(100) NOT NULL UNIQUE,
    mapped_title VARCHAR(500) NOT NULL,
    source_value VARCHAR(500), category VARCHAR(200), interpretation_description TEXT,
    risk_level VARCHAR(30), mapping_version VARCHAR(100) NOT NULL DEFAULT 'excel_001', active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS damaged_item_mapping (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mapped_code VARCHAR(100) NOT NULL UNIQUE,
    mapped_title VARCHAR(500) NOT NULL,
    source_value VARCHAR(500), category VARCHAR(200), interpretation_description TEXT,
    mapping_version VARCHAR(100) NOT NULL DEFAULT 'excel_001', active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS damage_type_mapping (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mapped_code VARCHAR(100) NOT NULL UNIQUE,
    mapped_title VARCHAR(500) NOT NULL,
    source_value VARCHAR(500), category VARCHAR(200), interpretation_description TEXT,
    mapping_version VARCHAR(100) NOT NULL DEFAULT 'excel_001', active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS financial_damage_type_mapping (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mapped_code VARCHAR(100) NOT NULL UNIQUE,
    mapped_title VARCHAR(500) NOT NULL,
    source_value VARCHAR(500), category VARCHAR(200), interpretation_description TEXT,
    mapping_version VARCHAR(100) NOT NULL DEFAULT 'excel_001', active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS property_type_mapping (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mapped_code VARCHAR(100) NOT NULL UNIQUE,
    mapped_title VARCHAR(500) NOT NULL,
    source_value VARCHAR(500), category VARCHAR(200), interpretation_description TEXT,
    mapping_version VARCHAR(100) NOT NULL DEFAULT 'excel_001', active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS structure_type_mapping (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mapped_code VARCHAR(100) NOT NULL UNIQUE,
    mapped_title VARCHAR(500) NOT NULL,
    source_value VARCHAR(500), category VARCHAR(200), interpretation_description TEXT,
    mapping_version VARCHAR(100) NOT NULL DEFAULT 'excel_001', active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS risk_density_mapping (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mapped_code VARCHAR(100) NOT NULL UNIQUE,
    mapped_title VARCHAR(500) NOT NULL,
    source_value VARCHAR(500), category VARCHAR(200), interpretation_description TEXT,
    risk_level VARCHAR(30), mapping_version VARCHAR(100) NOT NULL DEFAULT 'excel_001', active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS ownership_type_mapping (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mapped_code VARCHAR(100) NOT NULL UNIQUE,
    mapped_title VARCHAR(500) NOT NULL,
    source_value VARCHAR(500), category VARCHAR(200), interpretation_description TEXT,
    mapping_version VARCHAR(100) NOT NULL DEFAULT 'excel_001', active BOOLEAN NOT NULL DEFAULT TRUE
);

-- Add FK constraints only for columns that have a corresponding mapping domain.
ALTER TABLE clean_damage_data DROP CONSTRAINT IF EXISTS fk_clean_coverage;
ALTER TABLE clean_damage_data DROP CONSTRAINT IF EXISTS fk_clean_event_type;
ALTER TABLE clean_damage_data DROP CONSTRAINT IF EXISTS fk_clean_loss_location;
ALTER TABLE clean_damage_data DROP CONSTRAINT IF EXISTS fk_clean_occupation;
ALTER TABLE clean_damage_data DROP CONSTRAINT IF EXISTS fk_clean_occupation_group;
ALTER TABLE clean_damage_data DROP CONSTRAINT IF EXISTS fk_clean_damaged_item;
ALTER TABLE clean_damage_data DROP CONSTRAINT IF EXISTS fk_clean_damage_type;
ALTER TABLE clean_damage_data DROP CONSTRAINT IF EXISTS fk_clean_financial_damage_type;
ALTER TABLE clean_damage_data DROP CONSTRAINT IF EXISTS fk_clean_property_type;
ALTER TABLE clean_damage_data DROP CONSTRAINT IF EXISTS fk_clean_structure_type;
ALTER TABLE clean_damage_data DROP CONSTRAINT IF EXISTS fk_clean_risk_density;
ALTER TABLE clean_damage_data DROP CONSTRAINT IF EXISTS fk_clean_ownership_type;

ALTER TABLE clean_damage_data ADD CONSTRAINT fk_clean_coverage FOREIGN KEY (coverage_code) REFERENCES coverage_mapping(mapped_code);
ALTER TABLE clean_damage_data ADD CONSTRAINT fk_clean_event_type FOREIGN KEY (event_type_code) REFERENCES event_type_mapping(mapped_code);
ALTER TABLE clean_damage_data ADD CONSTRAINT fk_clean_loss_location FOREIGN KEY (loss_location_code) REFERENCES loss_location_mapping(mapped_code);
ALTER TABLE clean_damage_data ADD CONSTRAINT fk_clean_occupation FOREIGN KEY (occupation_code) REFERENCES occupation_mapping(mapped_code);
ALTER TABLE clean_damage_data ADD CONSTRAINT fk_clean_occupation_group FOREIGN KEY (occupation_group_code) REFERENCES occupation_group_mapping(mapped_code);
ALTER TABLE clean_damage_data ADD CONSTRAINT fk_clean_damaged_item FOREIGN KEY (damaged_item_code) REFERENCES damaged_item_mapping(mapped_code);
ALTER TABLE clean_damage_data ADD CONSTRAINT fk_clean_damage_type FOREIGN KEY (damage_type_code) REFERENCES damage_type_mapping(mapped_code);
ALTER TABLE clean_damage_data ADD CONSTRAINT fk_clean_financial_damage_type FOREIGN KEY (financial_damage_type_code) REFERENCES financial_damage_type_mapping(mapped_code);
ALTER TABLE clean_damage_data ADD CONSTRAINT fk_clean_property_type FOREIGN KEY (property_type_code) REFERENCES property_type_mapping(mapped_code);
ALTER TABLE clean_damage_data ADD CONSTRAINT fk_clean_structure_type FOREIGN KEY (structure_type_code) REFERENCES structure_type_mapping(mapped_code);
ALTER TABLE clean_damage_data ADD CONSTRAINT fk_clean_risk_density FOREIGN KEY (risk_density_code) REFERENCES risk_density_mapping(mapped_code);
ALTER TABLE clean_damage_data ADD CONSTRAINT fk_clean_ownership_type FOREIGN KEY (ownership_type_code) REFERENCES ownership_type_mapping(mapped_code);

